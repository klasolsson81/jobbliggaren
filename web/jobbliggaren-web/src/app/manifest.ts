import type { MetadataRoute } from "next";
import { getLocale, getTranslations } from "next-intl/server";

// Next.js 16 file convention: Web App Manifest. Background_color vit (matchar
// landing-light). theme_color = granskogsgrön #15603F (matchar grön-accent-identiteten
// ADR 0068 + sigill-logon, logo-översyn 2026-06-13) — ersätter tidigare navy.
// Manifest-konventionen får vara async i Next.js → description återanvänder
// `metadata.description` via next-intl (locale från cookie, samma som resten).
export default async function manifest(): Promise<MetadataRoute.Manifest> {
  const t = await getTranslations("metadata");
  const locale = await getLocale();
  return {
    name: "Jobbliggaren",
    short_name: "Jobbliggaren",
    description: t("description"),
    start_url: "/",
    display: "standalone",
    background_color: "#FFFFFF",
    theme_color: "#15603F",
    lang: locale,
    // Android installs and home-screen shortcuts need PNGs at 192 and 512 (an SVG alone is not enough), and a
    // maskable one so a launcher can crop it to any shape. Regenerated by scripts/generate-brand-icons.mjs.
    icons: [
      {
        src: "/icon.svg",
        type: "image/svg+xml",
        sizes: "any",
      },
      {
        src: "/icons/icon-192.png",
        type: "image/png",
        sizes: "192x192",
        purpose: "any",
      },
      {
        src: "/icons/icon-512.png",
        type: "image/png",
        sizes: "512x512",
        purpose: "any",
      },
      {
        src: "/icons/icon-maskable-512.png",
        type: "image/png",
        sizes: "512x512",
        purpose: "maskable",
      },
      {
        src: "/apple-icon",
        type: "image/png",
        sizes: "180x180",
      },
    ],
  };
}
